import React from 'react';
import type { DataOriginType } from '../types/api';
import { Cpu, BookOpen, Layers, Sparkles } from 'lucide-react';

interface BadgeProps {
  origin: DataOriginType;
  className?: string;
  size?: 'sm' | 'md';
}

export const Badge: React.FC<BadgeProps> = ({ origin, className = '', size = 'md' }) => {
  const sizeClasses = size === 'sm' ? 'px-2 py-0.5 text-xs' : 'px-2.5 py-1 text-xs font-medium';

  switch (origin) {
    case 'Real model output':
      return (
        <span
          className={`inline-flex items-center gap-1.5 rounded-full bg-emerald-950/80 text-emerald-400 border border-emerald-500/30 ${sizeClasses} ${className}`}
          title="Direct computation extracted from the local PyTorch model"
        >
          <Cpu className="w-3.5 h-3.5 animate-pulse text-emerald-400" />
          <span>Real model output</span>
        </span>
      );

    case 'Educational explanation':
      return (
        <span
          className={`inline-flex items-center gap-1.5 rounded-full bg-blue-950/80 text-blue-400 border border-blue-500/30 ${sizeClasses} ${className}`}
          title="Explains the mathematical or architectural concept"
        >
          <BookOpen className="w-3.5 h-3.5 text-blue-400" />
          <span>Educational explanation</span>
        </span>
      );

    case 'Illustrative diagram':
      return (
        <span
          className={`inline-flex items-center gap-1.5 rounded-full bg-amber-950/80 text-amber-400 border border-amber-500/30 ${sizeClasses} ${className}`}
          title="Conceptual architecture illustration"
        >
          <Layers className="w-3.5 h-3.5 text-amber-400" />
          <span>Illustrative diagram</span>
        </span>
      );

    case 'Gemini-written explanation':
      return (
        <span
          className={`inline-flex items-center gap-1.5 rounded-full bg-purple-950/80 text-purple-300 border border-purple-500/30 ${sizeClasses} ${className}`}
          title="Generated by optional Gemini API tutor"
        >
          <Sparkles className="w-3.5 h-3.5 text-purple-400" />
          <span>Gemini-written explanation</span>
        </span>
      );

    default:
      return null;
  }
};
